#ifndef RAW_MEMORY_H
#define RAW_MEMORY_H

#include "القلب/المكتبات/انواع.h"

/*
 * حدود كتلة "ذاكرة_خام()  ...  نهاية_ذاكرة"
 */
int raw_memory_is_start(const char *line);
int raw_memory_is_end(const char *line);

/* ================================================================
 * أوامر التحكم الكامل بالذاكرة الخام
 *
 * تشمل: قراءة/كتابة بأحجام مختلفة (8/16/32/64)، نسخ/تعبئة/مقارنة
 * كتلة ذاكرة، تخصيص/تحرير من الكومة، تخصيص صفحة فيزيائية، وربط
 * عنوان افتراضي بعنوان فيزيائي.
 *
 * ملاحظة: أوامر ذاكرة_اكتب( )/ذاكرة_اقرا( ) الأصلية (32 بت بدون
 * لاحقة رقمية) ما زالت تُعالَج في اوامر_اللغة.c كما كانت؛ الدوال هنا
 * تغطي كل ما هو إضافي فوقها.
 * ================================================================ */

/*
 * raw_memory_dispatch_statement
 *
 * يفحص p هل يطابق أحد أوامر الذاكرة الخام التي تُستخدم كسطر مستقل
 * (لا تُسنَد لمتغير)، مثل: ذاكرة_اكتب8/16/32/64, ذاكرة_انسخ,
 * ذاكرة_املأ, ذاكرة_حرر, ذاكرة_اربط.
 * كما يستقبل أوامر القراءة (ذاكرة_اقرا* وغيرها) عند استخدامها
 * كسطر مستقل، فيُنفّذها ويتجاهل قيمتها المُرجعة.
 *
 * matched: تُعاد 1 إذا كان p يطابق أحد هذه الأوامر، وإلا 0.
 * القيمة المُعادة من الدالة (فقط عند matched=1): 0 نجاح / -1 خطأ.
 */
int raw_memory_dispatch_statement(const char *p, int *matched);

/*
 * raw_memory_dispatch_value
 *
 * يفحص p هل يطابق أحد أوامر الذاكرة الخام التي "تُرجع قيمة" ويمكن
 * إسنادها إلى متغير، مثل: ذاكرة_اقرا8/16/32/64, ذاكرة_قارن,
 * ذاكرة_خصص, ذاكرة_خصص_صفحة.
 *
 * matched: تُعاد 1 إذا كان p يطابق أحد هذه الأوامر، وإلا 0.
 * value: تحمل القيمة الناتجة عند النجاح (matched=1 والقيمة المُعادة 0).
 * القيمة المُعادة من الدالة (فقط عند matched=1): 0 نجاح / -1 خطأ.
 */
int raw_memory_dispatch_value(const char *p, double *value, int *matched);

#endif
