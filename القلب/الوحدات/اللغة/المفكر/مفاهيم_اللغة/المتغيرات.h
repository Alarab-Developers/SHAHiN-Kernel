#ifndef المتغيرات_H
#define المتغيرات_H


#define MAX_VARIABLES 64
#define MAX_VARIABLE_NAME 64
#define MAX_VARIABLE_TEXT 256


/* ================================================================ */
/* أنواع المتغيرات                                                   */
/* ================================================================ */

typedef enum
{
    VARIABLE_NUMBER = 0,
    VARIABLE_TEXT

} variable_type_t;


/* ================================================================ */
/* النوع الفرعي للمتغير الرقمي                                        */
/*                                                                    */
/* يُكتشف تلقائياً من القيمة نفسها عند كل تعيين (variable_set):       */
/*                                                                    */
/*   س = 34                    ->  NUMBER_KIND_INT   (عدد صحيح)      */
/*   س = 34.444                ->  NUMBER_KIND_FLOAT  (عدد عائم)      */
/*   س = 34.4343424324234234   ->  NUMBER_KIND_FLOAT  (عدد عائم)      */
/*                                                                    */
/* أي قيمة تحتوي على جزء عشري تُخزَّن بنفس دقة float في لغة C          */
/* (32-بت، تقريباً 6-7 أرقام معنوية) — أي أنها تفقد نفس الدقة التي     */
/* كانت ستفقدها لو كُتبت "float x = ...;" في C تماماً.                */
/* ================================================================ */

typedef enum
{
    NUMBER_KIND_INT = 0,
    NUMBER_KIND_FLOAT

} number_kind_t;


/* ================================================================ */
/* المتغير                                                            */
/* ================================================================ */

typedef struct
{
    char name[MAX_VARIABLE_NAME];

    /*
     * القيمة الرقمية
     */
    double value;

    /*
     * النص
     */
    char text[MAX_VARIABLE_TEXT];

    /*
     * نوع المتغير
     */
    variable_type_t type;

    /*
     * النوع الفرعي عند كون المتغير رقمياً (type == VARIABLE_NUMBER):
     * صحيح أم عائم؟ (انظر تعريف number_kind_t أعلاه)
     */
    number_kind_t number_kind;

    /*
     * هل المتغير مستخدم؟
     */
    int used;

} variable_t;


/* ================================================================ */
/* تهيئة مدير المتغيرات                                              */
/* ================================================================ */

void variables_init(void);


/* ================================================================ */
/* إنشاء أو تعديل متغير رقمي                                        */
/* ================================================================ */

int variable_set(
    const char *name,
    double value
);


/* ================================================================ */
/* قراءة متغير رقمي                                                  */
/* ================================================================ */

int variable_get(
    const char *name,
    double *value
);


/* ================================================================ */
/* معرفة نوع متغير رقمي: صحيح أم عائم                                 */
/*                                                                    */
/* ترجع 0 عند النجاح و -1 إذا كان المتغير غير موجود أو نصياً          */
/* ================================================================ */

int variable_get_kind(
    const char *name,
    number_kind_t *kind
);


/* ================================================================ */
/* تحويل متغير رقمي إلى نص جاهز للطباعة، مع مراعاة نوعه:              */
/*                                                                    */
/*   صحيح -> بدون فاصلة عشرية        (مثال: "34")                    */
/*   عائم  -> بدقة float كما في C     (مثال: "34.444000")             */
/*                                                                    */
/* مفيدة لأي أمر طباعة (مثل اطبع()) بدلاً من استدعاء                  */
/* double_to_string يدوياً بدقة ثابتة لكل الأنواع                     */
/* ================================================================ */

int variable_to_string(
    const char *name,
    char *buffer,
    int buffer_size
);


/* ================================================================ */
/* إنشاء أو تعديل متغير نصي                                         */
/* ================================================================ */

int variable_set_text(
    const char *name,
    const char *text
);


/* ================================================================ */
/* قراءة متغير نصي                                                   */
/* ================================================================ */

int variable_get_text(
    const char *name,
    char *text,
    int text_size
);


#endif
